#!/usr/bin/env node
/**
 * One-shot data migration: MySQL (Infomaniak) -> PostgreSQL (Hetzner).
 *
 * Copies every table in dependency order, preserving primary keys so
 * foreign-key references survive. Resets each table's SERIAL sequence
 * after the load.
 *
 * The destination tables MUST already exist (db/init/01-schema.sql is
 * applied by the postgis container on first start).
 *
 * Usage (from the project root):
 *
 *   MYSQL_HOST=2h6995.myd.infomaniak.com MYSQL_USER=2h6995_atlas_use \
 *   MYSQL_PASS='...' MYSQL_DB=2h6995_atlas_sn \
 *   PG_HOST=localhost PG_USER=atlas PG_PASS='...' PG_DB=atlas \
 *   node scripts/migrate-mysql-to-pg.js
 *
 * Add --truncate to wipe the destination tables before loading
 * (default behaviour aborts if any destination table is non-empty).
 */

const mysql = require('mysql2/promise');
const { Client } = require('pg');

const MYSQL_OPTS = {
  host: process.env.MYSQL_HOST,
  port: parseInt(process.env.MYSQL_PORT || '3306', 10),
  user: process.env.MYSQL_USER,
  password: process.env.MYSQL_PASS,
  database: process.env.MYSQL_DB,
};

const PG_OPTS = {
  host: process.env.PG_HOST || 'localhost',
  port: parseInt(process.env.PG_PORT || '5432', 10),
  user: process.env.PG_USER,
  password: process.env.PG_PASS,
  database: process.env.PG_DB,
};

const TRUNCATE = process.argv.includes('--truncate');

// Load order respects FK dependencies. Each entry: [tableName, columns[]].
// `columns` excludes auto-managed ones (geom is regenerated by the trigger
// from lat/lon, no need to copy).
const TABLES = [
  ['dytaels', [
    'id', 'name', 'slug', 'description',
    'bounds_sw_lat', 'bounds_sw_lon', 'bounds_ne_lat', 'bounds_ne_lon',
    'default_zoom', 'active', 'created_at',
  ]],
  ['users', [
    'id', 'email', 'password', 'name', 'surname', 'phone',
    'organization', 'dytael_id', 'role', 'confirmed',
    'created_at', 'last_login',
  ]],
  ['custom_fields', [
    'id', 'field_key', 'field_label', 'field_type',
    'required', 'dytael_id', 'created_at',
  ]],
  ['initiatives', [
    'id', 'initiative', 'description', 'village', 'commune', 'zone_intervention',
    'actor_type', 'year', 'activities', 'lat', 'lon', 'location_type',
    'contact_email', 'contact_phone', 'person_name',
    'website', 'social_media', 'videos', 'extra_fields', 'status',
    'created_at', 'user_id', 'dytael_id', 'parent_id',
    'bailleurs', 'organisation', 'point_contact', 'duree',
  ]],
  ['initiative_locations', [
    'id', 'initiative_id', 'label', 'lat', 'lon',
    'village', 'commune', 'is_primary', 'created_at',
  ]],
  ['photos', [
    'id', 'initiative_id', 'filename', 'uploaded_at',
  ]],
];

// Columns that must be passed as JSON to PG (JSONB columns).
const JSON_COLUMNS = new Set([
  'activities', 'social_media', 'videos', 'extra_fields',
]);

function buildPlaceholders(start, count) {
  const out = [];
  for (let i = 0; i < count; i++) out.push(`$${start + i}`);
  return out.join(', ');
}

function adaptValue(col, val) {
  if (val == null) return null;
  if (JSON_COLUMNS.has(col)) {
    // mysql2 returns JSON columns either as parsed objects or strings.
    if (typeof val === 'string') {
      try { JSON.parse(val); return val; } catch { return JSON.stringify(val); }
    }
    return JSON.stringify(val);
  }
  // Booleans: mysql2 returns 0/1, PG expects boolean
  if (typeof val === 'number' && (col === 'active' || col === 'confirmed' || col === 'required' || col === 'is_primary')) {
    return val === 1;
  }
  return val;
}

async function main() {
  const my = await mysql.createConnection(MYSQL_OPTS);
  const pg = new Client(PG_OPTS);
  await pg.connect();

  console.log(`Connected. Source ${MYSQL_OPTS.user}@${MYSQL_OPTS.host}/${MYSQL_OPTS.database}`);
  console.log(`            Target ${PG_OPTS.user}@${PG_OPTS.host}/${PG_OPTS.database}`);

  try {
    if (TRUNCATE) {
      const list = TABLES.map(([t]) => t).reverse().join(', ');
      console.log(`Truncating destination tables: ${list}`);
      await pg.query(`TRUNCATE TABLE ${list} RESTART IDENTITY CASCADE`);
    } else {
      for (const [table] of TABLES) {
        const r = await pg.query(`SELECT COUNT(*)::int AS n FROM ${table}`);
        if (r.rows[0].n > 0) {
          throw new Error(
            `Destination table "${table}" already has ${r.rows[0].n} rows. ` +
            `Re-run with --truncate to wipe first.`
          );
        }
      }
    }

    for (const [table, cols] of TABLES) {
      const colList = cols.join(', ');
      const [rows] = await my.query(`SELECT ${colList} FROM ${table}`);
      console.log(`${table}: ${rows.length} row(s)`);
      if (rows.length === 0) continue;

      const placeholders = rows.map((_, i) =>
        `(${buildPlaceholders(i * cols.length + 1, cols.length)})`
      ).join(', ');

      const params = [];
      for (const row of rows) {
        for (const col of cols) {
          params.push(adaptValue(col, row[col]));
        }
      }

      await pg.query(
        `INSERT INTO ${table} (${colList}) VALUES ${placeholders}`,
        params
      );
    }

    // Reset every SERIAL sequence so future inserts don't collide.
    for (const [table] of TABLES) {
      await pg.query(
        `SELECT setval(pg_get_serial_sequence('${table}', 'id'),
                       COALESCE((SELECT MAX(id) FROM ${table}), 0) + 1,
                       false)`
      );
    }

    console.log('Migration done.');
  } finally {
    await my.end();
    await pg.end();
  }
}

main().catch((err) => {
  console.error('Migration failed:', err);
  process.exit(1);
});
